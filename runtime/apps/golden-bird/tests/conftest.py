def gt(monkeypatch):
    """golden_tools from app\\, reloaded so each test can point DATA / STUDIO_HOME at its own temp folder."""
    import golden_tools
    mod = importlib.reload(golden_tools)
    yield mod
    importlib.reload(golden_tools)
