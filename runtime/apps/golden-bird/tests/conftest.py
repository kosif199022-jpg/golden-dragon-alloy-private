"""Shared helpers for the «الطائر الذهبي» (Golden Bird) tests.

Outside app\\ on purpose (app\\ is generated by forge\\make_golden_bird.py). Rules: no network, no API key, no window, no
Claude call, and nothing written outside pytest's temp folders. Studio programs are never executed: the install test
unpacks a tiny zip made here, with a text file named like an exe.
"""
import ast
import importlib
import os
import sys
from pathlib import Path

import pytest

sys.dont_write_bytecode = True

TESTS = Path(__file__).resolve().parent
GB = TESTS.parent
APP = Path(os.environ.get("GB_APP_DIR") or GB / "app")
FORGE = GB / "forge"
if str(APP) not in sys.path:
    sys.path.insert(0, str(APP))


def read(rel, root=APP):
    return (Path(root) / rel).read_text(encoding="utf-8-sig")


def tree(rel="app.py"):
    return ast.parse(read(rel), filename=rel)


