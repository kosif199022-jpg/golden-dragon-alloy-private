"""🔌 API مخصص (gd_patches/gd_custom_api.py): wired into the generator and present in the generated app."""
import ast
import importlib.util
from pathlib import Path

GD = Path(__file__).resolve().parents[1]


def _mod():  # loads the patch module (also proves it imports cleanly)
    sp = importlib.util.spec_from_file_location("gd_custom_api", GD / "forge" / "gd_patches" / "gd_custom_api.py")
    m = importlib.util.module_from_spec(sp)
    sp.loader.exec_module(m)
    return m


def test_generator_applies_the_patch():
    forge = (GD / "forge" / "make_golden_dragon.py").read_text(encoding="utf-8")
    assert 'gd_patches" / "gd_custom_api.py"' in forge and "cx.patch_app(" in forge and "cx.patch_ui(" in forge


def test_patch_fits_the_current_app_before_the_knowledge_patch():
    """app/ is only regenerated by the forge (never edited by hand). Prove the patch applies to it with the generator's
    exact-count rule, in the generator's order: before gd_knowledge, which adds the page's second </style>."""
    m = _mod()
    app = (GD / "app" / "app.py").read_text(encoding="utf-8")
    ui = (GD / "app" / "ui" / "index.html").read_text(encoding="utf-8")
    ui = ui[: ui.rindex("</style>")] + ui[ui.rindex("</style>") + len("</style>"):]   # drop gd_knowledge's block end

    def sub(t, old, new, count=1, name=""):
        assert t.count(old) == count, (name, t.count(old))
        return t.replace(old, new)

    out = m.patch_app(app, sub)
    ast.parse(out)
    assert '"custom": "🔌 API مخصص"' in out and "cx_loop(self)" in out
    assert "cxKey" in m.patch_ui(ui, sub)
    forge = (GD / "forge" / "make_golden_dragon.py").read_text(encoding="utf-8")
    assert forge.index("cx.patch_ui(") < forge.index('"gd_knowledge"')


def test_key_never_in_settings_and_base_is_normalised():
    import re
    src = (GD / "forge" / "gd_patches" / "gd_custom_api.py").read_text(encoding="utf-8")
    assert "keyring" in src and "custom-api:" in src            # the key lives in the OS keyring, not in settings.json
    fn = re.search(r"^def cx_norm_base\(base\):\n(?:    .*\n)+", src, re.M).group(0)   # injected into app.py as text
    ns = {"re": re}
    exec(fn, ns)
    norm = ns["cx_norm_base"]
    assert norm("https://openrouter.ai/api/v1/") == "https://openrouter.ai/api/v1"
    assert norm("api.openai.com/v1/chat/completions") == "https://api.openai.com/v1"
