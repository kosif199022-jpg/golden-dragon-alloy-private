"""Shared helpers for the «التنين الذهبي» (Golden Dragon) tests.

Outside app\\ on purpose (app\\ is generated by forge\\make_golden_dragon.py). Rules: no network, no API key, no window, no
Claude call, nothing written outside pytest's temp folders, and no program from the index is executed (doctor only asks
shutil.which and whether a Python module can be found).
"""
import ast
import importlib
import os
import sys
from pathlib import Path

import pytest

sys.dont_write_bytecode = True

TESTS = Path(__file__).resolve().parent
GD = TESTS.parent
APP = Path(os.environ.get("GD_APP_DIR") or GD / "app")
FORGE = GD / "forge"
DESK = GD.parent                                    # «مهارات»
GB = DESK / "الطائر الذهبي"
if str(APP) not in sys.path:
    sys.path.insert(0, str(APP))


def read(rel, root=APP):
    return (Path(root) / rel).read_text(encoding="utf-8-sig")


def tree(rel="app.py"):
    return ast.parse(read(rel), filename=rel)


