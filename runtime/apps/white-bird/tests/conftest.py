def read(rel, root=APP):
    return (Path(root) / rel).read_text(encoding="utf-8-sig")


_trees = {}


def tree(rel, root=APP):
    key = (str(root), rel)
    if key not in _trees:
        _trees[key] = ast.parse(read(rel, root), filename=rel)
    return _trees[key]


def find_def(node, *names):
    """The (nested) def/class reached by following names, e.g. find_def(tree('app.py'), 'Session', 'dispatch')."""
    for name in names:
        node = next((n for n in getattr(node, "body", []) if isinstance(n, (ast.FunctionDef, ast.ClassDef)) and n.name == name), None)
        if node is None:
            raise AssertionError(f"{'.'.join(names)} not found")
    return node


def compared_constants(fn, var):
    """String constants that `var` is compared with (== or in (...)) anywhere inside fn."""
    out = set()
    for n in ast.walk(fn):
        if isinstance(n, ast.Compare) and isinstance(n.left, ast.Name) and n.left.id == var:
            for op, comp in zip(n.ops, n.comparators):
                if isinstance(op, ast.Eq) and isinstance(comp, ast.Constant):
                    out.add(comp.value)
                elif isinstance(op, ast.In) and isinstance(comp, (ast.Tuple, ast.List, ast.Set)):
                    out |= {e.value for e in comp.elts if isinstance(e, ast.Constant)}
    return out


def mcp_control_tools():
    """mcp_control.py is a stdio MCP server: importing it would start its read loop, so its TOOLS are read through ast
    (only the COMMON and TOOLS assignments are executed)."""
    t = tree("mcp_control.py")
    loops = [n for n in t.body if isinstance(n, ast.For) and "stdin" in ast.dump(n.iter)]
    assert loops, "mcp_control.py no longer has its top-level stdin loop: it may be importable now; update this test"
    keep = [n for n in t.body if isinstance(n, ast.Assign) and any(getattr(x, "id", "") in ("COMMON", "TOOLS") for x in n.targets)]
    ns = {}
    exec(compile(ast.Module(body=keep, type_ignores=[]), "mcp_control.py", "exec"), ns)
    return ns["TOOLS"]


def snapshot(root):
    root = Path(root)
    if not root.exists():
        return {}
    return {p.relative_to(root).as_posix(): (p.stat().st_size, p.stat().st_mtime_ns) for p in root.rglob("*") if p.is_file()}


