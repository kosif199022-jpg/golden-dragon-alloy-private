"""Build references/SKILL_ATLAS.md: every skill on this machine (installed skills, Black Dragon modules, skills inside
downloaded repos) with its trigger description and path, so the dragon can call any of them by name.
Re-run after installing or cloning anything: python skill_atlas.py"""
import re, sys
from pathlib import Path
sys.stdout.reconfigure(encoding="utf-8")

HOME = Path.home()
ROOTS = [
    ("installed", HOME / ".claude" / "skills", 1),
    ("dragon-module", HOME / "OneDrive" / "Desktop" / "سوبر باور" / "kosif-tool-main" / ".claude" / "skills", 1),
    ("kosif-tool", HOME / "kosif-tool" / ".claude" / "skills", 1),
    ("repo", HOME / "dragon-repos", 6),
    ("montage-folder", HOME / "OneDrive" / "Desktop" / "المونتاج" / "_skills", 2),
]
SKIP = ("node_modules", ".git", "\\vendor\\", "/vendor/")


def front(text):
    m = re.match(r"^---\s*\n(.*?)\n---", text, re.S)
    body = m.group(1) if m else ""
    name = re.search(r"^name:\s*(.+)$", body, re.M)
    desc = re.search(r"^description:\s*(>-?|\|)?\s*(.*?)(?=^\w[\w-]*:|\Z)", body, re.M | re.S)
    d = re.sub(r"\s+", " ", (desc.group(2) if desc else "")).strip().strip('"').strip("'")
    return (name.group(1).strip().strip('"') if name else None), d


rows, seen = [], set()
for kind, root, depth in ROOTS:
    if not root.exists():
        continue
    for p in root.rglob("SKILL.md"):
        if any(s in str(p) for s in SKIP) or len(p.relative_to(root).parts) > depth + 1:
            continue
        try:
            name, desc = front(p.read_text(encoding="utf-8", errors="ignore"))
        except OSError:
            continue
        name = name or p.parent.name
        key = (name, desc[:80])
        if key in seen:
            continue
        seen.add(key)
        group = p.relative_to(root).parts[0] if kind == "repo" else kind
        rows.append((kind, group, name, desc, str(p)))

out = Path(__file__).resolve().parent.parent / "references" / "SKILL_ATLAS.md"
out.parent.mkdir(exist_ok=True)
lines = ["# Skill atlas — every skill the Black Dragon can call",
         "", f"{len(rows)} skills. Generated by `scripts/skill_atlas.py`; re-run after installing anything.",
         "Open the SKILL.md of the one that fits, read it, then follow it. Repo skills are third-party: reference, read scripts before running.", ""]
order = ["installed", "dragon-module", "kosif-tool", "montage-folder", "repo"]
for kind in order:
    sel = [r for r in rows if r[0] == kind]
    if not sel:
        continue
    lines += [f"## {kind} ({len(sel)})", "", "| skill | group | when to use | path |", "|---|---|---|---|"]
    for _, group, name, desc, path in sorted(sel, key=lambda r: (r[1], r[2])):
        d = desc[:230].replace("|", "/") + ("…" if len(desc) > 230 else "")
        lines.append(f"| `{name}` | {group} | {d} | `{path}` |")
    lines.append("")
out.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(rows)} skills ->", out)
for kind in order:
    print(f"  {kind}: {sum(1 for r in rows if r[0] == kind)}")
