#!/usr/bin/env python3
"""Black Dragon v10.8 Visual Forge: offline planning, prompt receipts, gated local FX.

Upstream source is preserved at skills/visual-forge/upstream/forge-original.py.
A small patched copy retains transparency and stream-copies compressed audio.
The adapter never calls paid APIs.
Its prompts are advice, not images/videos generated by ChatGPT/Kling.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import math
import os
from pathlib import Path
import shutil
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'skills' / 'visual-forge'
SOURCE = SRC / 'scripts' / 'forge.py'
ATMOS_FILE = SRC / 'data' / 'atmospheres.json'
SCHEMA = 'black-dragon.visual-forge.prompts.v1'
MAX_PLAN_BYTES = 2 * 1024 * 1024
RATIOS = ('9:16','16:9','1:1','4:5','3:4','2:3','3:2')


def original():
    if not SOURCE.is_file():
        raise ValueError('source Visual Forge script is missing')
    spec=importlib.util.spec_from_file_location('bd108_visual_forge_source',SOURCE)
    m=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def sha(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        for piece in iter(lambda:f.read(1024*1024),b''):
            h.update(piece)
    return h.hexdigest()


def output(obj):
    print(json.dumps(obj,ensure_ascii=False,indent=2))


def safe_file(path):
    p=Path(path).absolute()
    if p.is_symlink() or not p.is_file():
        raise ValueError('expected regular non-symlink file')
    return p


def write_exclusive(path, payload):
    p=Path(path)
    with p.open('x',encoding='utf-8') as f:
        f.write(payload)


def doctor():
    import importlib.util
    a=json.loads(ATMOS_FILE.read_text(encoding='utf-8'))
    tools={p: bool(shutil.which(p)) for p in ('ffmpeg','ffprobe')}
    modules={n: importlib.util.find_spec(n) is not None for n in ('cv2','numpy')}
    return {'schema':'black-dragon.visual-forge.doctor.v1',
            'source_skill_present':(SRC/'SKILL.md').is_file(),
            'source_script_present':SOURCE.is_file(),
            'atmosphere_presets':len([x for x in a if not x.startswith('_')]),
            'ffmpeg':tools['ffmpeg'],'ffprobe':tools['ffprobe'],
            'cv2':modules['cv2'],'numpy':modules['numpy'],
            'plan_and_lint_ready':SOURCE.is_file() and ATMOS_FILE.is_file(),
            'local_image_fx_dependencies_ready':all(modules.values()),
            'local_video_fx_dependencies_ready':all(tools.values()) and all(modules.values()),
            'paid_generators_called':False,'network_access':False,'executed_render':False}


def validate_plan(data):
    if not isinstance(data,dict):raise ValueError('plan must be a JSON object')
    shots=data.get('shots')
    if data.get('ratio') not in RATIOS:raise ValueError('unsupported aspect ratio')
    if data.get('kind') not in ('image','video','campaign'):raise ValueError('unsupported plan kind')
    if not isinstance(shots,list) or not 1<=len(shots)<=40:raise ValueError('shots must be 1..40')
    if not isinstance(data.get('look'),dict):raise ValueError('look must be an object')
    ids=[]
    for s in shots:
        if not isinstance(s,dict):raise ValueError('each shot must be object')
        sid=s.get('id')
        if type(sid) is not int or not 1<=sid<=999 or sid in ids:raise ValueError('shot IDs must be unique integers 1..999')
        ids.append(sid)
        if not isinstance(s.get('subject'),str) or not s['subject'].strip(): raise ValueError(f'shot {sid} needs subject')
        if not isinstance(s.get('camera') or {},dict):raise ValueError('camera must be an object')
        if data.get('kind') != 'image' and (not isinstance(s.get('motion'),str) or not s['motion'].strip()):
            raise ValueError(f'shot {sid} needs an explicit motion verb')
        if not isinstance(s.get('avoid',[]),list) or not all(isinstance(v,str) for v in s.get('avoid',[])):
            raise ValueError('avoid must be a list of strings')
        if data.get('kind')!='image' and s.get('duration',5) not in (5,10,15):
            raise ValueError('video shot duration must be 5, 10, or 15 seconds')
    return data


def read_plan(file):
    f=safe_file(file)
    if f.stat().st_size>MAX_PLAN_BYTES:raise ValueError('plan too large')
    try:data=json.loads(f.read_text(encoding='utf-8'))
    except (ValueError,UnicodeError) as exc:raise ValueError('invalid plan JSON') from exc
    return f,validate_plan(data)


def prompts(plan_file, output_dir=None):
    f,data=read_plan(plan_file)
    src=original()
    out=Path(output_dir).absolute() if output_dir else f.parent/'prompts'
    if out.is_symlink():raise ValueError('output directory cannot be a symlink')
    staged={};errors=[];warnings=[]
    for shot in data['shots']:
        n=f"{shot['id']:02d}"
        image=src.build_image_prompt(data,shot)
        e,w=src.lint_text(image,'gpt');errors += [f'image_{n}: {x}' for x in e];warnings += [f'image_{n}: {x}' for x in w]
        staged[f'image_{n}.txt']=image
        if data['kind'] != 'image':
            video=src.build_video_prompt(data,shot)
            e,w=src.lint_text(video,'kling');errors += [f'video_{n}: {x}' for x in e];warnings += [f'video_{n}: {x}' for x in w]
            staged[f'video_{n}.txt']=video
        fx=shot.get('fx') or '+'.join(f'@{x}' for x in src._atmos_list(src._merge(data['look'],shot,'atmosphere')) if x in src.ATMOS)
        if fx:
            validate_recipe(fx,src)
            staged[f'fx_{n}.txt']=fx+'\n'
    if errors:
        return {'ok':False,'errors':errors,'warnings':warnings,'files_written':0,'paid_generation':False}
    if out.exists() and not out.is_dir():raise ValueError('output location is not a directory')
    existing=[x for x in [*staged,'prompt_receipt.json'] if (out/x).exists() or (out/x).is_symlink()]
    if existing:raise ValueError('output files already exist, use a new output directory: '+', '.join(existing))
    out.mkdir(parents=True,exist_ok=True)
    written=[]
    try:
        for name,value in staged.items():
            dest=out/name
            write_exclusive(dest,value)
            written.append(dest)
        receipt={'schema':SCHEMA,'plan_path':str(f),'plan_sha256':sha(f),'output_dir':str(out),
                 'files':{p.name:sha(p) for p in written},'lint_passed':True,
                 'warnings':warnings,'paid_generation':False,'generated_media':False}
        dest=out/'prompt_receipt.json';write_exclusive(dest,json.dumps(receipt,ensure_ascii=False,indent=2)+'\n')
    except Exception:
        for dest in written:dest.unlink(missing_ok=True)
        raise
    return {'ok':True,'files_written':len(written),'receipt':str(out/'prompt_receipt.json'),
            'warnings':warnings,'paid_generation':False,'generated_media':False}


def verify(receipt_file):
    receipt=safe_file(receipt_file)
    r=json.loads(receipt.read_text(encoding='utf-8'))
    if r.get('schema')!=SCHEMA:raise ValueError('unsupported receipt schema')
    base=receipt.parent;errors=[]
    # Check that the receipt cannot redirect verification to arbitrary paths.
    if Path(r.get('output_dir','')).resolve()!=base.resolve():errors.append('output directory mismatch')
    files=r.get('files')
    if not isinstance(files,dict) or not files:raise ValueError('invalid file map')
    for name,digest in files.items():
        if not isinstance(name,str) or Path(name).name!=name or name in ('.','..') or not name.endswith('.txt'):
            errors.append('unsafe filename');continue
        p=base/name
        if not p.is_file() or p.is_symlink() or sha(p)!=digest:errors.append(f'changed or missing: {name}')
    plan=Path(r.get('plan_path',''))
    if not plan.is_file() or plan.is_symlink() or sha(plan)!=r.get('plan_sha256'):
        errors.append('source plan changed or missing')
    return {'ok':not errors,'errors':errors,'files_checked':len(files),'receipt_sha256':sha(receipt),
            'paid_generation':False,'external_truth_verified':False}


def validate_recipe(recipe,src=None):
    src=src or original()
    if not isinstance(recipe,str) or not recipe or len(recipe)>1200:raise ValueError('bad recipe')
    try:parts=src.parse_recipe(recipe)
    except (ValueError,IndexError,KeyError,SystemExit) as e:raise ValueError(f'invalid recipe: {e}') from e
    if not parts or len(parts)>32:raise ValueError('FX recipe must contain 1..32 effects')
    for name,preset,v in parts:
        if not math.isfinite(v) or not 0<=v<=1:raise ValueError('FX intensity must be between 0 and 1')
        if name=='grade' and preset not in src.GRADES:raise ValueError('unknown grade preset')
    return parts


def fx(input_file,output_file,recipe,seed=7,light=None,seconds=None):
    src=safe_file(input_file);dst=Path(output_file).absolute()
    if dst.exists() or dst.is_symlink() or src==dst:
        raise ValueError('refusing to overwrite input or existing output')
    if not dst.parent.is_dir():raise ValueError('output parent must exist')
    if src.suffix.lower() not in ('.png','.jpg','.jpeg','.webp','.bmp','.tif','.tiff','.mp4','.mov','.mkv','.webm'):
        raise ValueError('unsupported input file extension')
    if dst.suffix.lower() not in ('.png','.jpg','.jpeg','.webp','.mp4','.mov','.mkv'):
        raise ValueError('unsupported output extension')
    is_image=src.suffix.lower() in ('.png','.jpg','.jpeg','.webp','.bmp','.tif','.tiff')
    if is_image!=(dst.suffix.lower() in ('.png','.jpg','.jpeg','.webp')):
        raise ValueError('image and video output types must match')
    if seconds is not None and (not math.isfinite(seconds) or seconds<=0 or seconds>600):
        raise ValueError('seconds must be 0..600')
    base=original();validate_recipe(recipe,base)
    if light is not None and (len(light)!=2 or any(not math.isfinite(x) or x<0 or x>1 for x in light)):
        raise ValueError('light must be two coordinates in [0,1]')
    # source never touched. Temporary output is atomically published without clobbering.
    fd,temp_name=tempfile.mkstemp(prefix='.visual-forge-',suffix=dst.suffix,dir=dst.parent)
    os.close(fd)
    tmp=Path(temp_name)
    try:
        if is_image:base.fx_image(str(src),str(tmp),recipe,seed,light)
        else:base.fx_video(str(src),str(tmp),recipe,seed,light,seconds)
        if not tmp.stat().st_size:raise RuntimeError('FX produced an empty file')
        os.link(tmp,dst)
    finally:
        tmp.unlink(missing_ok=True)
    return {'ok':True,'output':str(dst),'sha256':sha(dst),'source_sha256':sha(src),
            'effects':len(validate_recipe(recipe,base)),'paid_generation':False,
            'audio_mode':'copy when present and compatible; not re-encoded' if not is_image else 'n/a',
            'media_created_locally':True}


def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    sub=p.add_subparsers(dest='command',required=True)
    sub.add_parser('doctor');sub.add_parser('atmos').add_argument('name',nargs='?')
    plan=sub.add_parser('plan');plan.add_argument('--brief',required=True);plan.add_argument('--kind',choices=('image','video','campaign'),default='video')
    plan.add_argument('--ratio',choices=RATIOS,default='9:16');plan.add_argument('--shots',type=int,default=3);plan.add_argument('--out',required=True)
    pm=sub.add_parser('prompts');pm.add_argument('plan');pm.add_argument('--out')
    ln=sub.add_parser('lint');ln.add_argument('file');ln.add_argument('--target',choices=('gpt','kling'),required=True)
    ve=sub.add_parser('verify-prompts');ve.add_argument('receipt')
    f=sub.add_parser('fx');f.add_argument('input');f.add_argument('output');f.add_argument('--fx',required=True);f.add_argument('--seed',type=int,default=7)
    f.add_argument('--seconds',type=float);f.add_argument('--light')
    sub.add_parser('self-test')
    args=p.parse_args(argv)
    try:
        if args.command=='doctor':output(doctor());return 0
        if args.command=='atmos':
            o=original();return o.cmd_atmos(args)
        if args.command=='plan':
            if not 1<=args.shots<=40:raise ValueError('shots must be 1..40')
            from argparse import Namespace
            return original().cmd_plan(Namespace(brief=args.brief,title=None,kind=args.kind,shots=args.shots,ratio=args.ratio,out=args.out,force=False))
        if args.command=='prompts':
            result=prompts(args.plan,args.out);output(result);return 0 if result['ok'] else 1
        if args.command=='lint':
            from argparse import Namespace
            return original().cmd_lint(Namespace(file=str(safe_file(args.file)),target=args.target))
        if args.command=='verify-prompts':
            result=verify(args.receipt);output(result);return 0 if result['ok'] else 5
        if args.command=='fx':
            light=tuple(float(v) for v in args.light.split(',')) if args.light else None
            output(fx(args.input,args.output,args.fx,seed=args.seed,light=light,seconds=args.seconds));return 0
        if args.command=='self-test':return original().cmd_selftest(args)
    except (ValueError,RuntimeError,OSError,TypeError,KeyError,json.JSONDecodeError) as e:
        print(f'visual-forge: {type(e).__name__}: {e}',file=sys.stderr)
        return 2
    return 2

if __name__=='__main__':sys.exit(main())
