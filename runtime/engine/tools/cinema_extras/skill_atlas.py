#!/usr/bin/env python3
"""skill-atlas — map every skill on this machine (installed, kosif-tool, downloaded repos, montage folder).

    dragon.py tool skill-atlas                  # summary only: how many skills per source (writes nothing)
    dragon.py tool skill-atlas --write          # rebuild references/SKILL_ATLAS.md inside the skill
    dragon.py tool skill-atlas --out ATLAS.md   # write somewhere else (an existing file needs --force)
    dragon.py tool skill-atlas --json           # rows as JSON on stdout

Each row: name, group, trigger description, path (home folder shown as ~). Re-run after installing or cloning
anything. Repo skills are third-party text: read their scripts before running any of them.
v10.14: was a raw script that rebuilt the bundled atlas on any argument (even --help); now writing is explicit.
"""
import argparse, json, os, re, sys
from pathlib import Path

HOME = Path.home()
PKG = Path(__file__).resolve().parents[2]
DEFAULT_OUT = PKG / "references" / "SKILL_ATLAS.md"
ROOTS = [
    ("installed", HOME / ".claude" / "skills", 1),
    ("kosif-tool", HOME / "kosif-tool" / ".claude" / "skills", 1),
    ("kosif-own", HOME / "kosif-own" / "kosif-tool" / ".claude" / "skills", 1),
    ("repo", Path(os.environ.get("DRAGON_REPOS") or (HOME / "dragon-repos")), 6),
    ("montage-folder", HOME / "OneDrive" / "Desktop" / "المونتاج" / "_skills", 2),
]
SKIP = {"node_modules", ".git", "vendor", "__pycache__"}
ORDER = [r[0] for r in ROOTS]


def front(text):
    m = re.match(r"^---\s*\n(.*?)\n---", text, re.S)
    body = m.group(1) if m else ""
    name = re.search(r"^name:\s*(.+)$", body, re.M)
    desc = re.search(r"^description:\s*(>-?|\|)?\s*(.*?)(?=^\w[\w-]*:|\Z)", body, re.M | re.S)
    d = re.sub(r"\s+", " ", (desc.group(2) if desc else "")).strip().strip('"').strip("'")
    return (name.group(1).strip().strip('"') if name else None), d


def tilde(p):
    try:
        return "~/" + Path(p).relative_to(HOME).as_posix()
    except ValueError:
        return Path(p).as_posix()


def scan(roots=ROOTS):
    rows, seen = [], set()
    for kind, root, depth in roots:
        if not root.is_dir():
            continue
        for p in root.rglob("SKILL.md"):
            rel = p.relative_to(root).parts
            if SKIP & set(rel) or len(rel) > depth + 1:
                continue
            try:
                name, desc = front(p.read_text(encoding="utf-8", errors="ignore"))
            except OSError:
                continue
            name = name or p.parent.name
            key = (name, desc[:80])
            if key in seen:
                continue
            seen.add(key)
            for h in (str(HOME), HOME.as_posix()):          # descriptions may quote the owner's home folder
                desc = desc.replace(h, "~")
            rows.append({"kind": kind, "group": rel[0] if kind == "repo" else kind, "name": name,
                         "description": desc, "path": tilde(p)})
    return rows


def render(rows):
    lines = ["# Skill atlas — every skill the Black Dragon can call", "",
             f"{len(rows)} skills. Generated by `dragon.py tool skill-atlas --write`; re-run after installing anything.",
             "Open the SKILL.md of the one that fits, read it, then follow it. Repo skills are third-party: reference, "
             "read scripts before running.", ""]
    for kind in ORDER:
        sel = [r for r in rows if r["kind"] == kind]
        if not sel:
            continue
        lines += [f"## {kind} ({len(sel)})", "", "| skill | group | when to use | path |", "|---|---|---|---|"]
        for r in sorted(sel, key=lambda r: (r["group"], r["name"])):
            d = r["description"][:230].replace("|", "/") + ("…" if len(r["description"]) > 230 else "")
            lines.append(f"| `{r['name']}` | {r['group']} | {d} | `{r['path']}` |")
        lines.append("")
    return "\n".join(lines)


def main(argv=None):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(prog="dragon.py tool skill-atlas", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true", help=f"rebuild {DEFAULT_OUT.relative_to(PKG).as_posix()}")
    g.add_argument("--out", help="write the atlas to this path")
    ap.add_argument("--force", action="store_true", help="overwrite an existing --out file")
    ap.add_argument("--json", action="store_true", help="print rows as JSON")
    a = ap.parse_args(argv)
    rows = scan()
    if a.json:
        print(json.dumps(rows, ensure_ascii=False, indent=1))
    else:
        print(f"{len(rows)} skills")
        for kind in ORDER:
            print(f"  {kind}: {sum(r['kind'] == kind for r in rows)}")
    target = DEFAULT_OUT if a.write else (Path(a.out).resolve() if a.out else None)
    if target is None:
        if not a.json:
            print("(ملخص بس. `--write` بيحدّث المرجع، و`--out PATH` بيكتب في مكان تاني)")
        return 0
    if a.out and target.exists() and not a.force:
        print(f"موجود: {target} (استخدم --force)", file=sys.stderr); return 2
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(rows), encoding="utf-8")
    print(f"-> {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
