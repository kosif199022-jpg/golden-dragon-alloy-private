class FXEngine:
    def __init__(self, w: int, h: int, fps: float, recipe: str, seed: int = 7, light=None, still=False):
        np, cv2 = _np()
        self.np, self.cv2 = np, cv2
        self.w, self.h, self.fps, self.still = w, h, max(fps, 1.0), still
        self.rng = np.random.default_rng(seed)
        items = parse_recipe(recipe)
        self.fx = sorted(items, key=lambda x: FX_ORDER.index(x[0]))
        self.light = (light[0] * w, light[1] * h) if light else (0.5 * w, 0.12 * h)
        self.k = max(w, h) / 1920.0  # resolution scale
        self._init_state()

    # -- helpers
    def _noise(self, h, w, cells, octaves=3):
        np, cv2 = self.np, self.cv2
        acc = np.zeros((h, w), np.float32)
        amp, tot = 1.0, 0.0
        for o in range(octaves):
            c = max(2, int(cells * (2 ** o)))
            small = self.rng.random((max(2, int(c * h / max(h, w))) + 1, max(2, int(c * w / max(h, w))) + 1)).astype(np.float32)
            acc += amp * cv2.resize(small, (w, h), interpolation=cv2.INTER_CUBIC)
            tot += amp
            amp *= 0.5
        acc /= tot
        acc -= acc.min()
        acc /= max(acc.max(), 1e-6)
        return acc

    def _init_state(self):
        np = self.np
        w, h = self.w, self.h
        names = {n for n, _, _ in self.fx}
        self.st = {}
        if "fog" in names or "heat" in names:
            self.st["fog_tex"] = self._noise(h, w * 2, 5, 4)
        if "heat" in names:
            self.st["heat_tex"] = (self._noise(h * 2, w, 14, 2) - 0.5, self._noise(h * 2, w, 14, 2) - 0.5)
        yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
        self.st["grid"] = (xx, yy)
        if "vignette" in names:
            r = np.sqrt(((xx - w / 2) / (w / 2)) ** 2 + ((yy - h / 2) / (h / 2)) ** 2) / math.sqrt(2)
            self.st["vig"] = np.clip((r - 0.35) / 0.65, 0, 1) ** 1.6
        for n, _, v in self.fx:
            if n in ("rain", "snow", "dust", "embers"):
                dens = {"rain": 1 / 2200, "snow": 1 / 5000, "dust": 1 / 9000, "embers": 1 / 22000}[n]
                if n == "dust" and v >= 0.7:
                    dens = 1 / 2600
                N = max(20, int(v * w * h * dens / max(self.k, 0.5)))
                self.st[n] = {
                    "x": self.rng.random(N) * w,
                    "y": self.rng.random(N) * h,
                    "z": 0.25 + 0.75 * self.rng.random(N) ** 1.5,  # depth: 1 = near
                    "ph": self.rng.random(N) * 6.283,
                }
        if "lightning" in names:
            v = dict((n, v) for n, _, v in self.fx)["lightning"]
            gap = 3.5 / max(v, 0.1)
            self.st["flashes"] = list(np.cumsum(self.rng.uniform(gap * 0.5, gap * 1.5, 50)) - gap * 0.6)

    # -- effects (float32 BGR 0..1)
    def grade(self, f, preset, v):
        np = self.np
        sh, hi, sat, con, gain = GRADES.get(preset, GRADES["teal_orange"])
        g = f * np.array(gain, np.float32)
        lum = (0.114 * g[..., 0] + 0.587 * g[..., 1] + 0.299 * g[..., 2])[..., None]
        g = lum + (g - lum) * sat
        g = (g - 0.5) * con + 0.5
        sw = (1 - lum) ** 2
        hw = lum ** 2
        g = g + sw * np.array(sh, np.float32) + hw * np.array(hi, np.float32)
        if preset == "bleach":
            g = np.where(lum < 0.5, 2 * g * lum, 1 - 2 * (1 - g) * (1 - lum)) * 0.6 + g * 0.4
        return f + (np.clip(g, 0, 1) - f) * v

    def fog(self, f, v, t, tint=None):
        np = self.np
        tex = self.st["fog_tex"]
        off = int((t * 0.025 * self.w) % self.w)
        n = tex[:, off:off + self.w]
        h = self.h
        grad = np.linspace(0.45, 1.0, h, dtype=np.float32)[:, None]
        a = np.clip(v * 0.9 * (0.35 + 0.9 * n) * grad, 0, 0.92)[..., None]
        if tint:
            col = np.array(FOG_TINTS[tint], np.float32)
        else:
            mean = f.reshape(-1, 3).mean(0)
            col = np.clip(0.55 * np.array([0.80, 0.80, 0.78], np.float32) + 0.45 * (mean + 0.35), 0, 1)
        return f * (1 - a) + col * a

    def heat(self, f, v, t):
        np, cv2 = self.np, self.cv2
        tx, ty = self.st["heat_tex"]
        off = int((t * 0.08 * self.h) % self.h)
        dx = tx[off:off + self.h]
        dy = ty[off:off + self.h]
        amp = v * 7 * self.k
        grad = np.linspace(0.3, 1.0, self.h, dtype=np.float32)[:, None]
        xx, yy = self.st["grid"]
        return cv2.remap(f, xx + dx * amp * grad, yy + dy * amp * grad, cv2.INTER_LINEAR, borderMode=cv2.BORDER_REFLECT)

    def godrays(self, f, v):
        np, cv2 = self.np, self.cv2
        s = 4
        small = cv2.resize(f, (self.w // s, self.h // s), interpolation=cv2.INTER_AREA)
        lum = small.max(axis=2)
        thr = np.percentile(lum, 82)
        mask = np.clip((lum - thr) / max(1e-3, 1 - thr), 0, 1)[..., None] * small
        cx, cy = self.light[0] / s, self.light[1] / s
        acc = np.zeros_like(mask)
        samples = 28
        for i in range(samples):
            sc = 1.0 + i * 0.022
            M = np.float32([[sc, 0, cx * (1 - sc)], [0, sc, cy * (1 - sc)]])
            acc += cv2.warpAffine(mask, M, (mask.shape[1], mask.shape[0]), flags=cv2.INTER_LINEAR) * (1 - i / samples)
        acc /= samples * 0.5
        rays = cv2.resize(cv2.GaussianBlur(acc, (0, 0), 2), (self.w, self.h), interpolation=cv2.INTER_LINEAR)
        tint = np.array([0.85, 0.95, 1.05], np.float32)
        return 1 - (1 - f) * (1 - np.clip(rays * tint * v * 1.6, 0, 1))

    def _advance(self, P, vx, vy, t_dt):
        P["x"] = (P["x"] + vx * t_dt) % self.w
        P["y"] = (P["y"] + vy * t_dt) % self.h

    def rain(self, f, v, dt):
        np, cv2 = self.np, self.cv2
        P = self.st["rain"]
        k = self.k
        speed = (1400 + 1600 * P["z"]) * k
        ang = math.radians(12)
        if not self.still:
            self._advance(P, speed * math.sin(ang), speed * math.cos(ang), dt)
        layer = np.zeros((self.h, self.w), np.float32)
        L = (18 + 55 * P["z"]) * k * (1.0 if not self.still else 0.8)
        x0, y0 = P["x"], P["y"]
        x1, y1 = x0 - L * math.sin(ang), y0 - L * math.cos(ang)
        for i in range(len(x0)):
            cv2.line(layer, (int(x0[i]), int(y0[i])), (int(x1[i]), int(y1[i])),
                     float(0.18 + 0.45 * P["z"][i]), max(1, int(round(1.6 * k * P["z"][i]))), cv2.LINE_AA)
        layer = cv2.GaussianBlur(layer, (0, 0), 0.8 * max(k, 0.6))
        lum = cv2.GaussianBlur(f.max(axis=2), (0, 0), 25 * k)
        a = np.clip(layer * v * (0.55 + 0.8 * lum), 0, 1)[..., None]
        col = np.array([0.95, 0.93, 0.90], np.float32)
        return f * (1 - a) + col * a

    def snow(self, f, v, dt, t):
        np, cv2 = self.np, self.cv2
        P = self.st["snow"]
        k = self.k
        if not self.still:
            vy = (60 + 140 * P["z"]) * k
            P["y"] = (P["y"] + vy * dt) % self.h
            P["x"] = (P["x"] + (25 * k + 30 * k * np.sin(t * 1.3 + P["ph"])) * dt) % self.w
        layer = np.zeros((self.h, self.w), np.float32)
        for i in range(len(P["x"])):
            r = max(1, int(round((1.2 + 4.5 * P["z"][i] ** 2) * k)))
            cv2.circle(layer, (int(P["x"][i]), int(P["y"][i])), r, float(0.55 + 0.45 * P["z"][i]), -1, cv2.LINE_AA)
        layer = cv2.GaussianBlur(layer, (0, 0), 1.2 * max(k, 0.6))
        a = np.clip(layer * min(1.0, 0.5 + v), 0, 1)[..., None]
        return f * (1 - a) + np.array([1.0, 0.98, 0.96], np.float32) * a

    def dust(self, f, v, dt, t):
        np, cv2 = self.np, self.cv2
        P = self.st["dust"]
        k = self.k
        if not self.still:
            P["x"] = (P["x"] + (14 + 30 * v) * k * np.sin(t * 0.4 + P["ph"]) * dt + 40 * v * k * dt) % self.w
            P["y"] = (P["y"] + 10 * k * np.cos(t * 0.33 + P["ph"]) * dt) % self.h
        layer = np.zeros((self.h, self.w), np.float32)
        windy = v >= 0.7  # sandstorm: wind-driven horizontal streaks instead of floating motes
        if windy and not self.still:
            P["x"] = (P["x"] + 900 * v * k * P["z"] * dt) % self.w
        for i in range(len(P["x"])):
            x, y, z = int(P["x"][i]), int(P["y"][i]), P["z"][i]
            if windy:
                L = int((10 + 60 * z) * k)
                cv2.line(layer, (x - L, y + L // 8), (x, y), float(0.35 + 0.5 * z), max(1, int(1.4 * k * z)), cv2.LINE_AA)
            else:
                r = max(1, int(round((0.8 + 2.4 * z) * k)))
                cv2.circle(layer, (x, y), r, float(0.5 + 0.5 * z), -1, cv2.LINE_AA)
        layer = cv2.GaussianBlur(layer, (0, 0), 1.0 * max(k, 0.6))
        lum = cv2.GaussianBlur(f.max(axis=2), (0, 0), 15 * k)
        a = np.clip(layer * (0.25 + 1.2 * lum) * min(1.0, v + 0.3), 0, 1)[..., None]
        col = np.array([0.55, 0.78, 1.0] if windy else [0.80, 0.90, 1.0], np.float32)
        return f * (1 - a) + col * a

    def embers(self, f, v, dt, t):
        np, cv2 = self.np, self.cv2
        P = self.st["embers"]
        k = self.k
        if not self.still:
            P["y"] = (P["y"] - (60 + 160 * P["z"]) * k * dt) % self.h
            P["x"] = (P["x"] + 35 * k * np.sin(t * 2.1 + P["ph"]) * dt) % self.w
        layer = np.zeros((self.h, self.w), np.float32)
        flick = 0.6 + 0.4 * np.sin(t * 9 + P["ph"] * 3)
        for i in range(len(P["x"])):
            r = max(1, int(round((1 + 2.5 * P["z"][i]) * k)))
            cv2.circle(layer, (int(P["x"][i]), int(P["y"][i])), r, float(flick[i]), -1, cv2.LINE_AA)
        core = cv2.GaussianBlur(layer, (0, 0), 1.0 * max(k, 0.6))
        glow = cv2.GaussianBlur(layer, (0, 0), 6 * max(k, 0.6)) * 3
        e = (core + glow)[..., None] * np.array([0.15, 0.55, 1.0], np.float32) * v
        return 1 - (1 - f) * (1 - np.clip(e, 0, 1))

    def bloom(self, f, v):
        np, cv2 = self.np, self.cv2
        hi = np.clip((f - 0.68) / 0.32, 0, 1) * f
        b = cv2.GaussianBlur(hi, (0, 0), 22 * self.k) + cv2.GaussianBlur(hi, (0, 0), 60 * self.k)
        return 1 - (1 - f) * (1 - np.clip(b * v * 0.9, 0, 1))

    def leak(self, f, v, t):
        np = self.np
        xx, yy = self.st["grid"]
        w, h = self.w, self.h
        cx = w * (0.05 + 0.15 * math.sin(t * 0.35))
        cy = h * (0.25 + 0.2 * math.cos(t * 0.27))
        d = ((xx - cx) ** 2 + (yy - cy) ** 2) / (0.55 * max(w, h)) ** 2
        c2x, c2y = w * (0.95 - 0.1 * math.sin(t * 0.21)), h * 0.85
        d2 = ((xx - c2x) ** 2 + (yy - c2y) ** 2) / (0.4 * max(w, h)) ** 2
        lk = (np.exp(-d)[..., None] * np.array([0.10, 0.45, 1.0], np.float32)
              + 0.6 * np.exp(-d2)[..., None] * np.array([0.25, 0.20, 0.95], np.float32))
        return 1 - (1 - f) * (1 - np.clip(lk * v * 0.75, 0, 1))

    def lightning(self, f, v, t):
        np = self.np
        if self.still:
            return f
        e = 0.0
        for ft in self.st["flashes"]:
            dt = t - ft
            if 0 <= dt < 0.45:
                e = max(e, math.exp(-dt * 18) + 0.7 * math.exp(-((dt - 0.18) * 30) ** 2))
        if e <= 0.01:
            return f
        boost = e * v * 0.9
        return np.clip(f + boost * np.array([1.0, 0.92, 0.85], np.float32) * (0.35 + f), 0, 1)

    def vignette(self, f, v):
        return f * (1 - v * 0.75 * self.st["vig"])[..., None]

    def grain(self, f, v):
        np, cv2 = self.np, self.cv2
        hs, ws = max(2, self.h // 2), max(2, self.w // 2)
        n = self.rng.standard_normal((hs, ws)).astype(np.float32)
        n = cv2.resize(n, (self.w, self.h), interpolation=cv2.INTER_LINEAR)
        lum = f.mean(axis=2)
        amt = v * 0.07 * (0.4 + 1.6 * lum * (1 - lum))
        return f + (n * amt)[..., None]

    def apply(self, frame_u8, t: float):
        np = self.np
        f = frame_u8.astype(np.float32) / 255.0
        dt = 1.0 / self.fps
        for name, preset, v in self.fx:
            if name == "grade":
                f = self.grade(f, preset, v)
            elif name == "fog":
                f = self.fog(f, v, t, preset)
            elif name in ("heat", "leak", "lightning"):
                f = getattr(self, name)(f, v, t)
            elif name == "rain":
                f = self.rain(f, v, dt)
            elif name in ("snow", "dust", "embers"):
                f = getattr(self, name)(f, v, dt, t)
            else:
                f = getattr(self, name)(f, v)
        return (np.clip(f, 0, 1) * 255 + 0.5).astype(np.uint8)


def _probe(path: str) -> tuple[int, int, float, bool, float]:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries",
         "stream=width,height,r_frame_rate:stream_side_data=rotation:stream_tags=rotate:format=duration",
         "-of", "json", path], capture_output=True, text=True, encoding="utf-8", check=True).stdout
    j = json.loads(out)
    s = j["streams"][0]
    w, h = int(s["width"]), int(s["height"])
    num, den = s.get("r_frame_rate", "30/1").split("/")
    fps = float(num) / float(den or 1)
    rot = 0
    for sd in s.get("side_data_list", []) or []:
        if "rotation" in sd:
            rot = int(float(sd["rotation"]))
    if not rot and s.get("tags", {}).get("rotate"):
        rot = int(s["tags"]["rotate"])
    if abs(rot) % 180 == 90:
        w, h = h, w
    a = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "a", "-show_entries", "stream=index",
                        "-of", "csv=p=0", path], capture_output=True, text=True).stdout.strip()
    dur = float(j.get("format", {}).get("duration", 0) or 0)
    return w, h, fps, bool(a), dur


def fx_image(src: str, dst: str, recipe: str, seed: int, light) -> None:
    """Apply local FX and retain original alpha for transparent image assets."""
    np, cv2 = _np()
    img = cv2.imdecode(np.fromfile(src, np.uint8), cv2.IMREAD_UNCHANGED)
    if img is None:
        raise SystemExit(f"مش قادر أقرا الصورة: {src}")
    if img.ndim == 2:
        img = cv2.cvtColor(img, cv2.COLOR_GRAY2BGR)
    alpha = img[:, :, 3:4].copy() if img.shape[2] == 4 else None
    if alpha is not None and Path(dst).suffix.lower() in (".jpg", ".jpeg"):
        raise ValueError("JPEG cannot preserve source transparency: choose PNG")
    rgb = img[:, :, :3]
    h, w = rgb.shape[:2]
    eng = FXEngine(w, h, 24, recipe, seed, light, still=True)
    out = eng.apply(rgb, 0.0)
    if alpha is not None and Path(dst).suffix.lower() in (".png", ".webp", ".tiff", ".tif"):
        out = np.concatenate((out, alpha), axis=2)
    ext = Path(dst).suffix.lower() or ".png"
    params = [cv2.IMWRITE_JPEG_QUALITY, 96] if ext in (".jpg", ".jpeg") else []
    ok, buf = cv2.imencode(ext, out, params)
    if not ok:
        raise SystemExit("فشل الحفظ")
    buf.tofile(dst)

def fx_video(src: str, dst: str, recipe: str, seed: int, light, seconds: float | None) -> None:
    np, _ = _np()
    w, h, fps, has_audio, dur = _probe(src)
    eng = FXEngine(w, h, fps, recipe, seed, light)
    lim = ["-t", str(seconds)] if seconds else []
    dec = subprocess.Popen(["ffmpeg", "-v", "error", *lim, "-i", src, "-f", "rawvideo", "-pix_fmt", "bgr24", "-"],
                           stdout=subprocess.PIPE)
    enc_cmd = ["ffmpeg", "-y", "-v", "error", "-f", "rawvideo", "-pix_fmt", "bgr24", "-s", f"{w}x{h}",
               "-r", f"{fps:.6f}", "-i", "-"]
    if has_audio:
        # Stream-copy compressed audio rather than re-encoding it to AAC. The video
        # is encoded independently; do not use -shortest (can truncate video when
        # source audio is a little shorter than the picture).
        enc_cmd += [*lim, "-i", src, "-map", "0:v", "-map", "1:a:0", "-c:a", "copy"]
        if seconds is not None:
            enc_cmd += ["-t", str(seconds)]
    enc_cmd += ["-c:v", "libx264", "-preset", "slow", "-crf", "15", "-pix_fmt", "yuv420p",
                "-movflags", "+faststart", dst]
    enc = subprocess.Popen(enc_cmd, stdin=subprocess.PIPE)
    size = w * h * 3
    i = 0
    total = int((seconds or dur) * fps) or None
    while True:
        raw = dec.stdout.read(size)
        if len(raw) < size:
            break
        frame = np.frombuffer(raw, np.uint8).reshape(h, w, 3)
        enc.stdin.write(eng.apply(frame, i / fps).tobytes())
        i += 1
        if i % 24 == 0:
            print(f"\r  frame {i}" + (f"/{total}" if total else ""), end="", file=sys.stderr, flush=True)
    enc.stdin.close()
    dec.wait()
    rc = enc.wait()
    print(file=sys.stderr)
    if rc != 0 or i == 0:
        raise SystemExit(f"ffmpeg فشل (rc={rc}, frames={i})")


def cmd_fx(a) -> int:
    src, dst = a.input, a.output
    if Path(dst).resolve() == Path(src).resolve():
        print("ممنوع الكتابة فوق الملف الأصلي — اختار اسم خرج تاني", file=sys.stderr)
        return 2
    Path(dst).parent.mkdir(parents=True, exist_ok=True)
    light = tuple(float(x) for x in a.light.split(",")) if a.light else None
    parse_recipe(a.fx)  # validate early
    if Path(src).suffix.lower() in IMAGE_EXT:
        fx_image(src, dst, a.fx, a.seed, light)
    else:
        fx_video(src, dst, a.fx, a.seed, light, a.seconds)
    print(f"OK -> {dst}")
    return 0


