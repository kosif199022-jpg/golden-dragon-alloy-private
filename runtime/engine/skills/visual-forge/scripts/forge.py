def parse_recipe(recipe: str) -> list[tuple[str, str | None, float]]:
    """'rain:0.7,grade:golden:0.5,@storm' -> [(name, preset, intensity)]"""
    items = []
    for tok in re.split(r"[,+]", recipe):
        tok = tok.strip()
        if not tok:
            continue
        if tok.startswith("@"):
            name = tok[1:]
            if name not in ATMOS:
                raise SystemExit(f"atmosphere مش معروف: {name}")
            items.extend(parse_recipe(ATMOS[name]["fx"]))
            continue
        p = tok.split(":")
        if p[0] == "grade":
            preset = p[1] if len(p) > 1 else "teal_orange"
            items.append(("grade", preset, float(p[2]) if len(p) > 2 else 0.5))
        elif p[0] == "fog" and len(p) > 2:  # fog:0.6:sand -> tinted fog
            items.append(("fog", p[2], float(p[1])))
        else:
            items.append((p[0], None, float(p[1]) if len(p) > 1 else 0.5))
    known = {"grade", "rain", "snow", "fog", "dust", "embers", "godrays", "bloom", "leak",
             "lightning", "heat", "vignette", "grain"}
    for n, _, _ in items:
        if n not in known:
            raise SystemExit(f"مؤثر مش معروف: {n}. المتاح: {', '.join(sorted(known))}")
    # merge duplicates: keep the strongest
    merged: dict[tuple, float] = {}
    order = []
    for n, pr, v in items:
        key = (n, pr) if n in ("grade", "fog") else (n, None)
        if key not in merged:
            order.append(key)
            merged[key] = v
        else:
            merged[key] = max(merged[key], v)
    for n, pr, _ in items:
        if n == "fog" and pr and pr not in FOG_TINTS:
            raise SystemExit(f"لون ضباب مش معروف: {pr}. المتاح: {', '.join(FOG_TINTS)}")
    return [(k[0], k[1], merged[k]) for k in order]


