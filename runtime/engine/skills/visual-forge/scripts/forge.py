def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("plan")
    s.add_argument("--brief", required=True)
    s.add_argument("--title")
    s.add_argument("--kind", choices=["image", "video", "campaign"], default="video")
    s.add_argument("--shots", type=int, default=3)
    s.add_argument("--ratio", default="9:16")
    s.add_argument("--out", required=True)
    s.add_argument("--force", action="store_true")
    s.set_defaults(fn=cmd_plan)

    s = sub.add_parser("atmos")
    s.add_argument("name", nargs="?")
    s.set_defaults(fn=cmd_atmos)

    s = sub.add_parser("prompt")
    s.add_argument("plan")
    s.add_argument("--out")
    s.set_defaults(fn=cmd_prompt)

    s = sub.add_parser("lint")
    s.add_argument("file")
    s.add_argument("--target", choices=["gpt", "kling"], required=True)
    s.set_defaults(fn=cmd_lint)

    s = sub.add_parser("fx")
    s.add_argument("input")
    s.add_argument("output")
    s.add_argument("--fx", required=True, help='e.g. "rain:0.7,fog:0.3,grade:night_blue:0.5" or "@storm"')
    s.add_argument("--light", help="light source for godrays as fractions x,y (default 0.5,0.12)")
    s.add_argument("--seed", type=int, default=7)
    s.add_argument("--seconds", type=float, help="process only the first N seconds (preview)")
    s.set_defaults(fn=cmd_fx)

    s = sub.add_parser("self-test")
    s.set_defaults(fn=cmd_selftest)

    a = p.parse_args(argv)
    return a.fn(a)


