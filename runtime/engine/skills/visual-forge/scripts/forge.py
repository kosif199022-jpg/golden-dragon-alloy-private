# --------------------------------------------------------------------------- prompt builder

def _merge(look: dict, shot: dict, key: str) -> str:
    v = shot.get(key) or look.get(key) or ""
    return v.strip() if isinstance(v, str) else v


def _atmos_list(val: str) -> list[str]:
    return [x.strip() for x in re.split(r"[,+]", val or "") if x.strip()]


def _sentence(s: str) -> str:
    s = s.strip()
    if not s:
        return ""
    s = s[0].upper() + s[1:]
    return s if s[-1] in ".!?" else s + "."


def build_image_prompt(plan: dict, shot: dict) -> str:
    look = plan.get("look", {})
    cam = {**{"lens": look.get("lens", "")}, **{k: v for k, v in (shot.get("camera") or {}).items() if v}}
    medium = shot.get("medium") or plan.get("medium") or "cinematic photograph"
    atm_names = _atmos_list(_merge(look, shot, "atmosphere"))
    atm_phr = [ATMOS[n]["image"] if n in ATMOS else n for n in atm_names]

    parts = []
    head = f"Create a {medium} of {shot.get('subject', '').strip()}"
    if shot.get("action"):
        head += f", {shot['action'].strip()}"
    parts.append(_sentence(head))
    anchors = (shot["anchors"] if "anchors" in shot else look.get("anchors", "")).strip()
    if anchors:
        parts.append(_sentence(f"Keep these details exactly: {anchors}"))
    scene = " ".join(x for x in [shot.get("setting", ""), shot.get("time", "")] if x)
    if scene:
        parts.append(_sentence(f"Setting: {scene}"))
    if atm_phr:
        parts.append(_sentence("Atmosphere: " + "; ".join(atm_phr)))
    light = _merge(look, shot, "lighting")
    if light:
        parts.append(_sentence(f"Lighting: {light}"))
    cam_bits = [cam.get("framing", ""), cam.get("angle", ""), cam.get("lens", "")]
    cam_txt = ", ".join(x for x in cam_bits if x)
    if cam_txt:
        parts.append(_sentence(f"Camera: {cam_txt}"))
    if shot.get("composition"):
        parts.append(_sentence(f"Composition: {shot['composition']}"))
    style = _merge(look, shot, "style")
    color = _merge(look, shot, "color") or look.get("palette", "")
    if style:
        parts.append(_sentence(f"Style: {style}"))
    if color:
        parts.append(_sentence(f"Color: {color}"))
    text = (shot.get("text") or "").strip()
    if text:
        if re.search(r"[؀-ۿ]", text):
            parts.append("Leave clean, uncluttered negative space for a title that will be added later; do not render any text or letters.")
        else:
            parts.append(f'Render the text "{text}" exactly as written, spelled correctly, cleanly integrated into the design.')
    else:
        parts.append("No text, no watermark, no logos unless described.")
    avoid = shot.get("avoid") or []
    if avoid:
        parts.append(_sentence("Avoid: " + ", ".join(avoid)))
    parts.append(f"Aspect ratio {shot.get('ratio') or plan.get('ratio', '1:1')}.")
    return "\n".join(parts) + "\n"


def build_video_prompt(plan: dict, shot: dict) -> str:
    look = plan.get("look", {})
    atm_names = _atmos_list(_merge(look, shot, "atmosphere"))
    atm_mot = [ATMOS[n]["video"] if n in ATMOS else n for n in atm_names]
    lines = []
    subj = shot.get("subject", "").strip()
    anchors = (shot["anchors"] if "anchors" in shot else look.get("anchors", "")).strip()
    lines.append(_sentence(subj + (f" ({anchors})" if anchors else "")))
    if shot.get("motion"):
        lines.append(_sentence(shot["motion"]))
    if shot.get("setting"):
        lines.append(_sentence(shot["setting"]))
    if atm_mot:
        lines.append(_sentence(", ".join(atm_mot)))
    if shot.get("camera_move"):
        lines.append(_sentence("Camera: " + shot["camera_move"]))
    light = _merge(look, shot, "lighting")
    if light:
        lines.append(_sentence(light))
    style = _merge(look, shot, "style")
    if style:
        lines.append(_sentence(style))
    if shot.get("sound"):
        lines.append(_sentence("Sound: " + shot["sound"]))
    neg = shot.get("negative") or "morphing, warped hands, extra fingers, flicker, distorted face, text, watermark, jitter"
    body = " ".join(lines)
    return (
        f"PROMPT:\n{body}\n\nNEGATIVE:\n{neg}\n\nSETTINGS:\n"
        f"mode=image-to-video (start frame = image_{shot['id']:02d}.png)\n"
        f"duration={shot.get('duration', 5)}s  ratio={shot.get('ratio') or plan.get('ratio', '16:9')}  "
        f"quality=pro/master  cfg=0.5\n"
    )


def cmd_prompt(a) -> int:
    plan_path = Path(a.plan)
    plan = json.loads(plan_path.read_text(encoding="utf-8"))
    out = Path(a.out) if a.out else plan_path.parent / "prompts"
    out.mkdir(parents=True, exist_ok=True)
    bad = 0
    for shot in plan.get("shots", []):
        if not shot.get("subject"):
            print(f"shot {shot.get('id')}: subject فاضي — اتخطيت", file=sys.stderr)
            bad += 1
            continue
        n = f"{shot['id']:02d}"
        img = build_image_prompt(plan, shot)
        (out / f"image_{n}.txt").write_text(img, encoding="utf-8")
        errs, warns = lint_text(img, "gpt")
        report(f"image_{n}", errs, warns)
        bad += bool(errs)
        if plan.get("kind") != "image":
            vid = build_video_prompt(plan, shot)
            (out / f"video_{n}.txt").write_text(vid, encoding="utf-8")
            errs, warns = lint_text(vid, "kling")
            report(f"video_{n}", errs, warns)
            bad += bool(errs)
        fx = shot.get("fx") or "+".join(f"@{x}" for x in _atmos_list(_merge(plan.get("look", {}), shot, "atmosphere")) if x in ATMOS)
        if fx:
            (out / f"fx_{n}.txt").write_text(fx + "\n", encoding="utf-8")
    print(f"-> {out}")
    return 1 if bad else 0


