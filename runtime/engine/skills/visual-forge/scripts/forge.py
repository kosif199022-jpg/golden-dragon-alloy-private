def lint_text(txt: str, target: str) -> tuple[list[str], list[str]]:
    errs, warns = [], []
    low = txt.lower()
    body = low
    if target == "kling":
        m = re.search(r"prompt:\s*(.*?)(?:\n\s*negative:|\Z)", low, re.S)
        body = m.group(1) if m else low
    for f in FILLER:
        if re.search(r"(?<![a-z0-9])" + re.escape(f) + r"(?![a-z0-9])", body):
            warns.append(f"كلمة حشو «{f}» — الموديلات الحديثة بتتجاهلها أو بتعمل لوك بلاستيك؛ اوصف النور والخامة بدلها")
    if re.search(r"[؀-ۿ]", body):
        if target == "gpt":
            warns.append("فيه عربي جوه البرومنت — ChatGPT بيكتب العربي مقطّع/غلط غالبًا؛ اكتب البرومنت إنجليزي وحط النص العربي في البوست")
        else:
            errs.append("عربي جوه برومنت Kling — اكتبه إنجليزي (الصوت/الحوار العربي يتحط في المونتاج)")
    sentences = max(1, len(re.findall(r"[.!?](\s|$)", body)))
    if body.count(",") / sentences > 9:
        warns.append("شكله «شوربة كلمات» بفواصل — اكتب جمل كاملة: مين/بيعمل إيه/فين/النور/الكاميرا")
    if target == "gpt":
        if "lighting" not in body and "light" not in body:
            warns.append("مفيش وصف للنور — النور هو 70% من الاحترافية")
        if "aspect ratio" not in body:
            warns.append("مفيش aspect ratio")
        if len(body.split()) > 350:
            warns.append("البرومنت طويل جدًا (>350 كلمة) — التفاصيل الزيادة بتتلخبط")
        if len(body.split()) < 18:
            errs.append("البرومنت قصير جدًا (<18 كلمة) — الموديل هيكمّل من دماغه")
    if target == "kling":
        moves = sorted({m for m in CAM_MOVES if m in body})
        if len(moves) > 2:
            errs.append(f"حركات كاميرا كتير ({', '.join(moves)}) — حركة واحدة (أقصى حاجة اتنين) في كل لقطة")
        if not moves and "static" not in body and "locked" not in body and "camera:" not in body:
            warns.append("مفيش حركة كاميرا محددة — Kling هيختار لوحده؛ اكتب واحدة أو 'static locked-off camera'")
        if not re.search(MOTION_VERBS, body):
            errs.append("مفيش فعل حركة واضح — الفيديو هيطلع صورة بتتهز")
        if re.search(r"\b(no|without|don't|do not)\s+\w+", body):
            warns.append("نفي جوه البرومنت (no/without) — انقله لخانة NEGATIVE")
        if body.count(" then ") > 2:
            warns.append("أحداث متتالية كتير (then ×3+) — قسّمها على لقطات")
        if len(body) > 2500:
            errs.append("البرومنت أطول من 2500 حرف (حد Kling)")
        for b in CAM_BRANDS:
            if b in body:
                warns.append(f"اسم كاميرا «{b}» — وصف اللوك أحسن من اسم الماركة")
        dm = re.search(r"duration=(\d+)", low)
        if dm and int(dm.group(1)) not in (5, 10, 15):
            warns.append(f"duration={dm.group(1)}s — المدد الآمنة في Kling: 5 أو 10 (و15 في بعض الإصدارات)")
    return errs, warns


def report(name: str, errs: list[str], warns: list[str]) -> None:
    status = "FAIL" if errs else "PASS"
    print(f"[{status}] {name}")
    for e in errs:
        print(f"   ✗ {e}")
    for w in warns:
        print(f"   ! {w}")


def cmd_lint(a) -> int:
    txt = Path(a.file).read_text(encoding="utf-8")
    errs, warns = lint_text(txt, a.target)
    report(a.file, errs, warns)
    return 1 if errs else 0


