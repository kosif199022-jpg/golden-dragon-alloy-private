def shot_template(i: int, kind: str) -> dict:
    s = {
        "id": i,
        "purpose": "",
        "subject": "",
        "action": "",
        "setting": "",
        "time": "",
        "atmosphere": "",
        "lighting": "",
        "camera": {"lens": "", "angle": "", "framing": ""},
        "composition": "",
        "style": "",
        "color": "",
        "text": "",
        "avoid": [],
    }
    if kind != "image":
        s.update({"motion": "", "camera_move": "", "duration": 5, "sound": "", "negative": ""})
    s["fx"] = ""
    return s


def cmd_plan(a) -> int:
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    plan = {
        "title": a.title or a.brief[:60],
        "brief": a.brief,
        "kind": a.kind,
        "ratio": a.ratio,
        "medium": "cinematic photograph",
        "look": {
            "palette": "",
            "lighting": "",
            "lens": "",
            "atmosphere": "",
            "style": "",
            "color": "",
            "anchors": "",
        },
        "shots": [shot_template(i + 1, a.kind) for i in range(a.shots)],
    }
    pj = out / "plan.json"
    md = out / "plan.md"
    for p in (pj, md):
        if p.exists() and not a.force:
            print(f"موجود بالفعل (ماكتبتش فوقه): {p} — استخدم --force لو متأكد", file=sys.stderr)
            return 2
    pj.write_text(json.dumps(plan, ensure_ascii=False, indent=2), encoding="utf-8")
    rows = "\n".join(f"| {i + 1:02d} | | | | |" for i in range(a.shots))
    md.write_text(
        PLAN_MD.format(title=plan["title"], brief=a.brief, kind=a.kind, ratio=a.ratio,
                       shots=a.shots, shot_rows=rows),
        encoding="utf-8",
    )
    print(f"OK plan -> {md}\nOK spec -> {pj}")
    return 0


