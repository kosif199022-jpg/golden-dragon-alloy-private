def spin(brief, n, seed):
    if not 1 <= n <= 100:
        raise ValueError("spin count must be between 1 and 100")
    rng = random.Random(seed)
    keys = list(DECKS)
    out = []
    for i in range(n):
        pick = rng.sample(keys, k=min(6, len(keys)))
        out.append({"#": i + 1, "brief": brief, **{k: rng.choice(DECKS[k]) for k in pick}})
    return out


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("spin"); s.add_argument("brief"); s.add_argument("--n", type=int, default=6)
    s.add_argument("--seed", type=int); s.add_argument("--json", action="store_true")
    s = sub.add_parser("card"); s.add_argument("--n", type=int, default=3); s.add_argument("--seed", type=int)
    sub.add_parser("brief"); sub.add_parser("score")
    a = p.parse_args()
    if a.cmd == "spin":
        res = spin(a.brief, a.n, a.seed)
        if a.json:
            print(json.dumps(res, ensure_ascii=False, indent=1))
        else:
            for r in res:
                print(f"\n── بذرة {r['#']} ──")
                for k, v in r.items():
                    if k not in ("#", "brief"):
                        print(f"  {k}: {v}")
    elif a.cmd == "card":
        if not 1 <= a.n <= len(CARDS):
            p.error(f"card count must be 1..{len(CARDS)}")
        for c in random.Random(a.seed).sample(CARDS, k=a.n):
            print("• " + c)
    elif a.cmd == "brief":
        print(BRIEF)
    else:
        print(RUBRIC)


if __name__ == "__main__":
    main()
